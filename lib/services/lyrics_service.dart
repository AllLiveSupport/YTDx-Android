import 'app_logger.dart';
import 'auth_service.dart';

class LyricsService {
  static const String _tag = 'LyricsService';
  static Directory? _cacheDir;

  /// Retrieves lyrics for a track using a prioritized human-first architecture:
  /// 1. Local .lrc file next to audio or in app cache (Instant & Offline)
  /// 2. Video Description Official Lyrics aligned with YouTube Timestamps (100% human accuracy + sync)
  /// 3. Manual Uploader-Added Subtitles (!track.isAutoGenerated)
  /// 4. Auto-Generated AI Captions with Complete Sentence Reconstruction (No cut-off words)
  /// 5. Video Description Static Lyrics (Plaintext fallback)
  static Future<LyricsData?> getLyrics({
    required String videoId,
    String? filePath,
    String? title,
    String? artist,
  }) async {
    try {
      // 1. Check local .lrc file next to the downloaded audio file
      if (filePath != null && filePath.isNotEmpty) {
        final lrcPath = _getLrcPathForFile(filePath);
        final lrcFile = File(lrcPath);
        if (await lrcFile.exists()) {
          final content = await lrcFile.readAsString();
          final parsed = LyricsData.fromLrcString(content, source: 'Yerel .lrc (Çevrimdışı)');
          if (parsed != null && parsed.isNotEmpty) {
            AppLogger.info(_tag, 'Yerel .lrc dosyasından yüklendi: $lrcPath');
            return parsed;
          }
        }
      }

      // 2. Check application cache directory for previously saved lyrics
      final cachedFile = await _getCachedLrcFile(videoId);
      if (await cachedFile.exists()) {
        final content = await cachedFile.readAsString();
        final parsed = LyricsData.fromLrcString(content, source: 'Önbellek .lrc (Çevrimdışı)');
        if (parsed != null && parsed.isNotEmpty) {
          AppLogger.info(_tag, 'Uygulama önbelleğinden yüklendi: ${cachedFile.path}');
          return parsed;
        }
      }

      // 3. Fetch video details to inspect official description lyrics
      Video? video;
      List<String> descLyrics = [];
      YoutubeExplode? yt;
      try {
        yt = await AuthService.createYoutubeClient();
        video = await yt.videos.get(videoId);
        descLyrics = _extractLyricsLinesFromDescription(video.description);
      } catch (e) {
        AppLogger.info(_tag, 'Video bilgisi alınamadı ($videoId): $e');
      }

      // 4. Fetch closed captions tracks from YouTube
      ClosedCaptionManifest? manifest;
      if (yt != null) {
        try {
          manifest = await yt.videos.closedCaptions.getManifest(videoId);
        } catch (e) {
          AppLogger.info(_tag, 'Altyazı manifestosu alınamadı ($videoId): $e');
        }
      }

      final List<ClosedCaptionTrackInfo> tracks = manifest?.tracks.toList() ?? [];

      // Check for human-uploaded manual subtitle track (!isAutoGenerated)
      ClosedCaptionTrackInfo? manualTrack;
      final nonAutoTracks = tracks.where((t) => !t.isAutoGenerated).toList();
      if (nonAutoTracks.isNotEmpty) {
        for (final t in nonAutoTracks) {
          if (t.language.code.toLowerCase().startsWith('tr')) {
            manualTrack = t;
            break;
          }
        }
        manualTrack ??= nonAutoTracks.first;
      }

      // SCENARIO A: Human uploaded manual subtitles to YouTube
      if (manualTrack != null && yt != null) {
        try {
          final captionTrack = await yt.videos.closedCaptions.get(manualTrack);
          final rawLines = <LyricLine>[];
          for (final c in captionTrack.captions) {
            final cleaned = _cleanCaptionText(c.text);
            if (cleaned.isNotEmpty) {
              rawLines.add(LyricLine(time: c.offset, duration: c.duration, text: cleaned));
            }
          }
          if (rawLines.isNotEmpty) {
            rawLines.sort((a, b) => a.time.compareTo(b.time));
            final data = LyricsData(
              lines: rawLines,
              isSynced: true,
              source: 'Resmi Altyazı (Yükleyici)',
            );
            await _cacheLyricsResult(cachedFile, data, filePath: filePath, title: title, artist: artist);
            return data;
          }
        } catch (_) {}
      }

      // SCENARIO B: Uploader provided official lyrics in Video Description + YouTube has caption timestamps
      // We align the 100% human studio lyrics with YouTube's timestamps!
      if (descLyrics.isNotEmpty && tracks.isNotEmpty && yt != null) {
        try {
          ClosedCaptionTrackInfo? autoTrack;
          for (final t in tracks) {
            if (t.language.code.toLowerCase().startsWith('tr')) {
              autoTrack = t;
              break;
            }
          }
          autoTrack ??= tracks.first;
          final captionTrack = await yt.videos.closedCaptions.get(autoTrack);

          if (captionTrack.captions.isNotEmpty) {
            final alignedLines = _alignDescriptionWithCaptions(descLyrics, captionTrack.captions);
            if (alignedLines.length >= 4) {
              AppLogger.success(_tag, '✅ Açıklamadaki resmi sözler YouTube zamanlamasıyla mükemmel hizalandı (${alignedLines.length} satır)');
              final data = LyricsData(
                lines: alignedLines,
                isSynced: true,
                source: 'Resmi Sözler (Sanatçı / Açıklama)',
              );
              await _cacheLyricsResult(cachedFile, data, filePath: filePath, title: title, artist: artist);
              return data;
            }
          }
        } catch (e) {
          AppLogger.info(_tag, 'Açıklama hizalama hatası: $e');
        }
      }

      // SCENARIO C: No description lyrics found, but YouTube has auto-generated AI captions
      // We reconstruct sentences to prevent broken words or orphaned last words on new lines!
      if (tracks.isNotEmpty && yt != null) {
        try {
          ClosedCaptionTrackInfo? autoTrack;
          for (final t in tracks) {
            if (t.language.code.toLowerCase().startsWith('tr')) {
              autoTrack = t;
              break;
            }
          }
          autoTrack ??= tracks.first;
          final captionTrack = await yt.videos.closedCaptions.get(autoTrack);
          final reconstructedLines = _reconstructCompleteSentences(captionTrack.captions);

          if (reconstructedLines.isNotEmpty) {
            final data = LyricsData(
              lines: reconstructedLines,
              isSynced: true,
              source: 'YouTube Altyazı (Otomatik)',
            );
            await _cacheLyricsResult(cachedFile, data, filePath: filePath, title: title, artist: artist);
            return data;
          }
        } catch (e) {
          AppLogger.info(_tag, 'Otomatik altyazı işleme hatası: $e');
        }
      }

      // SCENARIO D: Only Description Lyrics without any captions on YouTube
      if (descLyrics.isNotEmpty) {
        final lines = <LyricLine>[];
        for (int i = 0; i < descLyrics.length; i++) {
          lines.add(LyricLine(
            time: Duration(seconds: i * 4),
            text: descLyrics[i],
          ));
        }
        final data = LyricsData(
          lines: lines,
          isSynced: false,
          source: 'Resmi Sözler (Açıklama)',
        );
        await _cacheLyricsResult(cachedFile, data, filePath: filePath, title: title, artist: artist);
        return data;
      }

      // SCENARIO E: Online Lyrics Fallback (LRCLIB & Web Lyrics Database)
      // Automatically kicks in if video has no subtitles or description lyrics
      final effectiveTitle = title ?? video?.title ?? '';
      final effectiveArtist = artist ?? video?.author ?? '';
      if (effectiveTitle.isNotEmpty) {
        AppLogger.info(_tag, 'YouTube altyazısı bulunamadı, çevrimiçi veritabanı taranıyor: $effectiveTitle');
        final onlineLyrics = await _fetchOnlineLyrics(
          rawTitle: effectiveTitle,
          rawArtist: effectiveArtist,
          duration: video?.duration,
        );
        if (onlineLyrics != null && onlineLyrics.isNotEmpty) {
          AppLogger.success(_tag, '✅ Şarkı sözleri çevrimiçi veritabanından başarıyla çekildi (${onlineLyrics.lines.length} satır)');
          await _cacheLyricsResult(cachedFile, onlineLyrics, filePath: filePath, title: title, artist: artist);
          return onlineLyrics;
        }
      }
    } catch (e) {
      AppLogger.error(_tag, 'Şarkı sözü getirme hatası ($videoId): $e');
    }

    return null;
  }

  /// Aligns official human-written description lyrics with YouTube caption timestamps
  /// Eliminates AI spelling mistakes and broken/split words completely!
  static List<LyricLine> _alignDescriptionWithCaptions(
    List<String> descLines,
    List<ClosedCaption> captions,
  ) {
    final result = <LyricLine>[];
    int currentCapIdx = 0;

    for (int lineIdx = 0; lineIdx < descLines.length; lineIdx++) {
      final descLine = descLines[lineIdx];
      // Normalize words for matching
      final descWords = descLine
          .toLowerCase()
          .replaceAll(RegExp(r'[^\w\sğüşıöç]'), '')
          .split(RegExp(r'\s+'))
          .where((w) => w.length >= 2)
          .toList();

      Duration? bestTime;
      int bestMatchCount = 0;
      int bestCapIdx = currentCapIdx;

      // Search forward in the next 12 caption chunks
      final searchWindow = (currentCapIdx + 12).clamp(0, captions.length);
      for (int i = currentCapIdx; i < searchWindow; i++) {
        final capText = captions[i]
            .text
            .toLowerCase()
            .replaceAll(RegExp(r'[^\w\sğüşıöç]'), '');

        int matches = 0;
        for (final w in descWords) {
          if (capText.contains(w)) matches++;
        }

        if (matches > bestMatchCount) {
          bestMatchCount = matches;
          bestTime = captions[i].offset;
          bestCapIdx = i;
        }
      }

      if (bestTime != null && bestMatchCount >= 1) {
        currentCapIdx = bestCapIdx;
        result.add(LyricLine(time: bestTime, text: descLine));
      } else {
        // Interpolate smoothly if an occasional line has no match
        Duration fallbackTime;
        if (result.isNotEmpty) {
          fallbackTime = result.last.time + const Duration(seconds: 4);
        } else {
          fallbackTime = Duration(seconds: lineIdx * 4);
        }
        result.add(LyricLine(time: fallbackTime, text: descLine));
      }
    }

    return result;
  }

  /// Reconstructs full sentences from fragmented YouTube AI caption chunks
  /// Guarantees that sentence endings and words are never chopped in half!
  static List<LyricLine> _reconstructCompleteSentences(List<ClosedCaption> captions) {
    final reconstructed = <LyricLine>[];
    String currentBuffer = '';
    Duration currentStart = Duration.zero;

    for (final c in captions) {
      final text = _cleanCaptionText(c.text);
      if (text.isEmpty) continue;

      if (currentBuffer.isEmpty) {
        currentStart = c.offset;
      }

      currentBuffer = currentBuffer.isEmpty ? text : '$currentBuffer $text';

      // Look for natural sentence breaks like . ! ? or major commas after sufficient length
      final sentenceEndings = RegExp(r'([.!?])\s+');
      var match = sentenceEndings.firstMatch(currentBuffer);

      while (match != null) {
        final sentence = currentBuffer.substring(0, match.start + 1).trim();
        if (sentence.length > 2) {
          reconstructed.add(LyricLine(time: currentStart, text: sentence));
        }
        currentBuffer = currentBuffer.substring(match.end).trim();
        currentStart = c.offset;
        match = sentenceEndings.firstMatch(currentBuffer);
      }
    }

    if (currentBuffer.trim().isNotEmpty) {
      reconstructed.add(LyricLine(time: currentStart, text: currentBuffer.trim()));
    }

    return reconstructed;
  }

  /// Extracts official lyrics lines from YouTube video descriptions
  static List<String> _extractLyricsLinesFromDescription(String description) {
    if (description.isEmpty) return [];

    final lower = description.toLowerCase();
    final markers = [
      'şarkı sözleri:',
      'şarkı sözü:',
      'şarkı sözleri',
      'sözler:',
      'sözler',
      'lyrics:',
      'song lyrics:',
    ];

    int startIndex = -1;
    for (final marker in markers) {
      final idx = lower.indexOf(marker);
      if (idx != -1) {
        startIndex = idx + marker.length;
        break;
      }
    }

    if (startIndex == -1) return [];

    final sub = description.substring(startIndex);
    final lines = <String>[];

    final stopMarkers = [
      'sosyal medya',
      'takip et',
      'follow',
      'yapımcı:',
      'abone ol',
      'menajerlik',
      'spotify:',
      'apple music:',
      'instagram:',
      'tiktok:',
      'twitter:',
      'tüm hakları',
    ];

    for (final raw in sub.split('\n')) {
      final trimmed = raw.trim();
      if (trimmed.isEmpty) continue;

      final rawLower = trimmed.toLowerCase();
      bool shouldStop = false;
      for (final stopMarker in stopMarkers) {
        if (rawLower.contains(stopMarker)) {
          shouldStop = true;
          break;
        }
      }

      if (shouldStop && lines.length >= 4) break;

      // Discard lines that look like credits or URLs
      if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) continue;
      if (trimmed.startsWith('(') && trimmed.endsWith(')') && trimmed.length < 20) continue;

      lines.add(trimmed);
    }

    return lines.length >= 4 ? lines : [];
  }

  /// Cleans noise from YouTube subtitle text like [Müzik], (Applause), HTML codes, etc.
  static String _cleanCaptionText(String raw) {
    var text = raw;

    // Decode HTML entities
    text = text
        .replaceAll('&quot;', '"')
        .replaceAll('&#39;', "'")
        .replaceAll('&amp;', '&')
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>')
        .replaceAll('&#160;', ' ')
        .replaceAll('&nbsp;', ' ');

    // Remove noise markers like [Müzik], [Alkış], [Gülüşmeler], (Music), (Applause)
    text = text.replaceAll(RegExp(r'\[.*?\]'), '');
    text = text.replaceAll(RegExp(r'\(.*?\)'), '');
    text = text.replaceAll(RegExp(r'[♪♫♬♩]'), '');

    // Trim extra spaces and line breaks
    text = text.replaceAll(RegExp(r'\s+'), ' ').trim();

    return text;
  }

  static String _getLrcPathForFile(String audioFilePath) {
    final dir = p.dirname(audioFilePath);
    final base = p.basenameWithoutExtension(audioFilePath);
    return p.join(dir, '$base.lrc');
  }

  static Future<File> _getCachedLrcFile(String videoId) async {
    _cacheDir ??= await getApplicationSupportDirectory();
    final lyricsDir = Directory(p.join(_cacheDir!.path, 'lyrics'));
    if (!await lyricsDir.exists()) {
      await lyricsDir.create(recursive: true);
    }
    return File(p.join(lyricsDir.path, '$videoId.lrc'));
  }

  static Future<void> _cacheLyricsResult(
    File cachedFile,
    LyricsData data, {
    String? filePath,
    String? title,
    String? artist,
  }) async {
    try {
      final content = data.toLrcFileContent(title: title, artist: artist);
      await cachedFile.writeAsString(content);
      AppLogger.info(_tag, '.lrc önbelleğe kaydedildi: ${cachedFile.path}');

      if (filePath != null && filePath.isNotEmpty) {
        final lrcPath = _getLrcPathForFile(filePath);
        await File(lrcPath).writeAsString(content);
        AppLogger.info(_tag, '.lrc şarkının yanına kaydedildi: $lrcPath');
      }
    } catch (e) {
      AppLogger.error(_tag, 'LRC kaydetme hatası: $e');
    }
  }

  /// Automatically downloads and saves .lrc alongside an audio download task
  static Future<void> cacheLyricsForDownload(String videoId, String audioFilePath, {String? title, String? artist}) async {
    try {
      await getLyrics(
        videoId: videoId,
        filePath: audioFilePath,
        title: title,
        artist: artist,
      );
    } catch (_) {}
  }

  /// Fetches lyrics from online database (LRCLIB) with synchronized .lrc priority
  static Future<LyricsData?> _fetchOnlineLyrics({
    required String rawTitle,
    String? rawArtist,
    Duration? duration,
  }) async {
    try {
      final parsed = _extractTrackAndArtist(rawTitle, fallbackArtist: rawArtist);
      final trackName = parsed['track'] ?? '';
      final artistName = parsed['artist'] ?? '';
      final primaryArtist = parsed['primary_artist'] ?? artistName;

      if (trackName.isEmpty) return null;

      final client = http.Client();
      try {
        // 1. Direct fetch with exact track_name and artist_name if artist is resolved
        if (artistName.isNotEmpty) {
          final queryParams = <String, String>{
            'track_name': trackName,
            'artist_name': artistName,
            if (duration != null && duration.inSeconds > 0)
              'duration': duration.inSeconds.toString(),
          };
          final uri = Uri.https('lrclib.net', '/api/get', queryParams);
          final res = await client.get(uri, headers: {
            'User-Agent': 'YTDxStudio/1.0 (Mobile Android; OpenSource)',
          }).timeout(const Duration(seconds: 4));

          if (res.statusCode == 200) {
            final json = jsonDecode(utf8.decode(res.bodyBytes)) as Map<String, dynamic>;
            final lyrics = _parseLrcLibResult(json);
            if (lyrics != null && lyrics.isNotEmpty) return lyrics;
          }
        }

        // 2. Multi-Tier Search Queries
        final searchQueries = <String>{
          if (artistName.isNotEmpty) '$artistName $trackName',
          if (primaryArtist.isNotEmpty && primaryArtist != artistName) '$primaryArtist $trackName',
          trackName,
          _cleanSearchQuery(rawTitle),
        }.toList();

        for (final q in searchQueries) {
          if (q.trim().isEmpty) continue;
          final uri = Uri.https('lrclib.net', '/api/search', {'q': q});
          final res = await client.get(uri, headers: {
            'User-Agent': 'YTDxStudio/1.0 (Mobile Android; OpenSource)',
          }).timeout(const Duration(seconds: 4));

          if (res.statusCode == 200) {
            final list = jsonDecode(utf8.decode(res.bodyBytes)) as List<dynamic>;
            if (list.isNotEmpty) {
              // Priority 1: record with syncedLyrics and close duration match
              Map<String, dynamic>? bestMatch;

              for (final item in list) {
                if (item is Map<String, dynamic>) {
                  final synced = (item['syncedLyrics'] as String?)?.trim();
                  if (synced != null && synced.isNotEmpty) {
                    if (duration != null && duration.inSeconds > 0) {
                      final itemDur = (item['duration'] as num?)?.toInt() ?? 0;
                      if ((itemDur - duration.inSeconds).abs() <= 5) {
                        bestMatch = item;
                        break;
                      }
                    }
                    bestMatch ??= item;
                  }
                }
              }

              // Fallback to first item if no synced found
              bestMatch ??= (list.first as Map<String, dynamic>);

              final lyrics = _parseLrcLibResult(bestMatch);
              if (lyrics != null && lyrics.isNotEmpty) return lyrics;
            }
          }
        }
      } finally {
        client.close();
      }
    } catch (e) {
      AppLogger.info(_tag, 'Çevrimiçi şarkı sözü arama hatası: $e');
    }
    return null;
  }

  /// Parses LRCLIB JSON payload into LyricsData
  static LyricsData? _parseLrcLibResult(Map<String, dynamic> data) {
    // Check synced lyrics first
    final synced = data['syncedLyrics'] as String?;
    if (synced != null && synced.trim().isNotEmpty) {
      final parsed = LyricsData.fromLrcString(synced, source: 'Çevrimiçi (Senkronize .lrc)');
      if (parsed != null && parsed.isNotEmpty) return parsed;
    }

    // Fallback to plain lyrics
    final plain = data['plainLyrics'] as String?;
    if (plain != null && plain.trim().isNotEmpty) {
      final rawLines = plain.split('\n').map((s) => s.trim()).where((s) => s.isNotEmpty).toList();
      if (rawLines.isNotEmpty) {
        final lines = <LyricLine>[];
        for (int i = 0; i < rawLines.length; i++) {
          lines.add(LyricLine(
            time: Duration(seconds: i * 4),
            text: rawLines[i],
          ));
        }
        return LyricsData(
          lines: lines,
          isSynced: false,
          source: 'Çevrimiçi (Web Sözleri)',
        );
      }
    }
    return null;
  }

  /// Cleans a query string from generic noise words
  static String _cleanSearchQuery(String text) {
    var s = text;
    s = s.replaceAll(RegExp(r'\[.*?\]'), '');
    s = s.replaceAll(RegExp(r'\(.*?\)', caseSensitive: false), '');
    s = s.replaceAll(RegExp(r'\b(official|video|klip|clip|audio|lyric|lyrics|müzik|şarkı|hd|hq|4k|remix|akustik|live)\b', caseSensitive: false), '');
    return s.replaceAll(RegExp(r'\s+'), ' ').trim();
  }

  /// Cleans typical YouTube title noise to extract pure track and artist name
  static Map<String, String> _extractTrackAndArtist(String rawTitle, {String? fallbackArtist}) {
    var title = rawTitle;

    // Clean brackets: [Official Video], [HD], [4K], etc.
    title = title.replaceAll(RegExp(r'\[.*?\]'), '');

    // Clean common parentheses tags
    title = title.replaceAll(
      RegExp(r'\((Official\s*(Music)?\s*Video|Offiziell|Video|Klip|Clip|Audio|Müzik|Lyric(s)?|Şarkı(sı)?|Prod(\.|\s).*?|feat\..*?|ft\..*?|4K|HD|HQ|1080p|2160p|Canlı|Live|Akustik|Acoustic|Remix).*?\)', caseSensitive: false),
      '',
    );

    // Clean unparenthesized trailing or leading clutter
    title = title.replaceAll(
      RegExp(r'\b(Official\s*(Music)?\s*Video|Official\s*Audio|Video\s*Klip|Klip|Clip|Lyric\s*Video|Lyrics|Sözleri|Canlı\s*Performans|Full\s*HD|1080p|4K|UHD)\b', caseSensitive: false),
      '',
    );

    title = title.replaceAll(RegExp(r'[\"“”]', caseSensitive: false), '');
    title = title.replaceAll(RegExp(r'\s+'), ' ').trim();

    String artist = '';
    String track = '';

    // Check for standard separators
    for (final sep in [' - ', ' – ', ' — ', ' | ', ' // ']) {
      if (title.contains(sep)) {
        final parts = title.split(sep);
        artist = parts[0].trim();
        track = parts.sublist(1).join(' - ').trim();
        break;
      }
    }

    // Clean fallback artist if it's a known distributor or has VEVO
    String cleanFallback = fallbackArtist ?? '';
    cleanFallback = cleanFallback.replaceAll(RegExp(r'VEVO\b', caseSensitive: false), '').trim();
    final isDistributor = RegExp(r'\b(netd|müzik|music|record(s)?|yapım|label|production)\b', caseSensitive: false).hasMatch(cleanFallback);

    if (artist.isEmpty) {
      track = title;
      if (!isDistributor) {
        artist = cleanFallback;
      }
    }

    // Clean track from remaining parentheses & feat/prod tags
    track = track.replaceAll(RegExp(r'\(.*?\)'), '').trim();
    track = track.replaceAll(RegExp(r'\b(feat\.|ft\.|prod\.).*', caseSensitive: false), '').trim();
    track = track.replaceAll(RegExp(r'[-–—|]+$'), '').trim();

    // Extract primary artist in collaborations ("Murat Boz & Ebru Gündeş" -> "Murat Boz")
    String primaryArtist = artist;
    final collabMatch = RegExp(r'^(.*?)(?:\s+(?:&|feat\.|ft\.|x|with|,)\s+)', caseSensitive: false).firstMatch(artist);
    if (collabMatch != null) {
      final first = collabMatch.group(1)?.trim() ?? '';
      if (first.isNotEmpty) primaryArtist = first;
    }

    return {
      'track': track,
      'artist': artist,
      'primary_artist': primaryArtist,
    };
  }
}
